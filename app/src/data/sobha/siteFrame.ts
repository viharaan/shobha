/**
 * SITE FRAME (2026-10-20) — the local metric frame every 3-D / geo layer shares.
 *
 * Origin = area centroid of the OpenStreetMap site polygon "Sobha One World"
 * (way 1427347113, developer-tagged, `source` = MoEFCC Parivesh EC proposal 135717602).
 * Axes: x = east, y = north, metres (equirectangular about the origin; error < 1 cm/km here).
 *
 * Cross-checks that make this the trusted frame:
 *  - OSM polygon area 198,808 m² = 49.13 ac vs 48 ac 15.32 guntas (48.38 ac) printed in the
 *    snapshot/master plan — within 1.6 %.
 *  - OSM wing footprints "Wing 1"…"Wing 14" reproduce the snapshot site-map arrangement.
 *  - With the corrected scale, the gap between Wings 12–14 and 5–8 (~100 m) holds the
 *    stated "~90 m dia" stadium field.
 *
 * PLAN → SITE transform: the earlier layout (amenities, landmarks, master-plan texture) was
 * read off the master-plan raster in an oversized frame. A least-squares similarity fit of the
 * 14 old wing estimates onto the 14 OSM wing centroids gives
 *    site = M · plan + T,  |M| = 0.2228 (scale), arg M = −4.97° (rotation), T = (−11.8, 35.5) m,
 * RMS residual 14.3 m (max 23.1 m). `fromPlan` applies it, so master-plan-derived positions
 * stay "estimated" but now sit at true scale.
 */

const OSM = 'OpenStreetMap contributors (ODbL)';

export const SITE_ORIGIN: LatLng = { lat: 13.06012, lng: 77.77588 };

const KX = 111320 * Math.cos((SITE_ORIGIN.lat * Math.PI) / 180); // m per degree lng
const KY = 110540; // m per degree lat

/** Plan→site similarity (complex multiply): M = a + ib. */
const M_RE = 0.221953;
const M_IM = -0.019305;
const T: [number, number] = [-11.8, 35.5];

export const PLAN_FIT = {
  scale: Math.hypot(M_RE, M_IM),
  rotationDeg: (Math.atan2(M_IM, M_RE) * 180) / Math.PI,
  translate: T,
  rmsResidualM: 14.3,
  maxResidualM: 23.1,
};

/** Old master-plan-raster frame [x, y] → site frame (metres, x east, y north). */
export function fromPlan([x, y]: [number, number]): SitePoint {
  return { x: M_RE * x - M_IM * y + T[0], y: M_IM * x + M_RE * y + T[1] };
}

/**
 * Master-plan PDF point → site metres with a registration fit (default export of
 * src/data/masterplanTraced.ts, `fit`; generated by tools/trace/masterplan.py).
 * Input: SOBHA_OneWorld_Masterplan.pdf page-2 points, top-left origin, y DOWN (pdftotext / pdftocairo
 * convention). site = R(rotRad)·(scale·(x, −y)) + (tx, ty). Independent of the older `fromPlan`.
 */
export function fromMasterplanPt([x, y]: [number, number], fit: MasterplanFit): SitePoint {
  const c = Math.cos(fit.rotRad) * fit.scaleMPerPt;
  const s = Math.sin(fit.rotRad) * fit.scaleMPerPt;
  return { x: c * x + s * y + fit.tx, y: s * x - c * y + fit.ty };
}

/** Site metres → [lng, lat]. */
export function siteToLngLat(p: SitePoint): [number, number] {
  return [SITE_ORIGIN.lng + p.x / KX, SITE_ORIGIN.lat + p.y / KY];
}

/** [lng, lat] → site metres. */
export function lngLatToSite(lng: number, lat: number): SitePoint {
  return { x: (lng - SITE_ORIGIN.lng) * KX, y: (lat - SITE_ORIGIN.lat) * KY };
}

